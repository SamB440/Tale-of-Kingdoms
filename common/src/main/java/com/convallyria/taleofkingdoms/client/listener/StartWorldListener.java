package com.convallyria.taleofkingdoms.client.listener;

import com.convallyria.taleofkingdoms.TaleOfKingdoms;
import com.convallyria.taleofkingdoms.TaleOfKingdomsAPI;
import com.convallyria.taleofkingdoms.client.TaleOfKingdomsClient;
import com.convallyria.taleofkingdoms.client.gui.generic.ScreenContinueConquest;
import com.convallyria.taleofkingdoms.client.gui.generic.ScreenStartConquest;
import com.convallyria.taleofkingdoms.client.gui.generic.owo.update.UpdateScreen;
import com.convallyria.taleofkingdoms.common.event.GameJoinCallback;
import com.convallyria.taleofkingdoms.common.event.WorldSessionStartCallback;
import com.convallyria.taleofkingdoms.common.event.WorldStopCallback;
import com.convallyria.taleofkingdoms.common.gamerule.TOKGameRules;
import com.convallyria.taleofkingdoms.common.listener.Listener;
import com.convallyria.taleofkingdoms.common.world.ConquestInstance;
import com.google.gson.Gson;
import com.google.gson.JsonIOException;
import com.google.gson.JsonSyntaxException;
import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
import net.minecraft.client.Minecraft;
import net.minecraft.network.chat.Component;
import net.minecraft.server.MinecraftServer;
import net.minecraft.world.entity.player.Player;
import org.jetbrains.annotations.Nullable;

import java.io.BufferedReader;
import java.io.File;
import java.io.FileReader;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;

@Environment(EnvType.CLIENT)
public class StartWorldListener extends Listener {

    private String worldName;
    private final List<Runnable> postJoin = new ArrayList<>();
    private boolean joined;

    @Nullable
    public String getWorldName() {
        return worldName;
    }

    public StartWorldListener() {
        WorldStopCallback.EVENT.register(() -> {
            if (!joined) return;
            if (TaleOfKingdoms.getAPI().getConquestInstanceStorage().mostRecentInstance().isEmpty()) return;

            ConquestInstance instance = TaleOfKingdoms.getAPI().getConquestInstanceStorage().mostRecentInstance().get();
            instance.save(worldName);
            TaleOfKingdoms.getAPI().getConquestInstanceStorage().removeConquest(worldName);
            this.joined = false;
        });

        WorldSessionStartCallback.EVENT.register(worldName -> {
            final TaleOfKingdomsAPI api = TaleOfKingdoms.getAPI();
            if (api == null) return;

            this.worldName = worldName;
            boolean loaded = load(worldName, api);

            File file = new File(api.getDataFolder() + "worlds/" + worldName + ConquestInstance.FILE_TYPE);

            // Already exists
            if (loaded) {
                Gson gson = api.getMod().getGson();
                // Load from json into class
                try (BufferedReader reader = new BufferedReader(new FileReader(file))) {
                    ConquestInstance instance = gson.fromJson(reader, ConquestInstance.class);
                    Runnable runnable = () -> api.executeOnMain(() -> {
                        // Check if file exists, but values don't. Game probably crashed?
                        if (instance == null || !instance.isLoaded()) {
                            Player entity = Minecraft.getInstance().player;
                            if (entity == null) return;

                            if (shouldAutoGenerateGuild()) {
                                createAutoGeneratedInstance(api, worldName, entity);
                            } else if (TaleOfKingdoms.CONFIG.mainConfig.showStartKingdomGUI) {
                                Minecraft.getInstance().setScreen(new ScreenStartConquest(worldName, file, entity));
                            } else {
                                Component keyName = TaleOfKingdomsClient.START_CONQUEST_KEYBIND.getTranslatedKeyMessage();
                                entity.displayClientMessage(Component.translatable("menu.taleofkingdoms.startconquest.closed", keyName.getString()), false);
                            }
                        } else if (instance.getStart() == null && !shouldAutoGenerateGuild()
                                && TaleOfKingdoms.CONFIG.mainConfig.showStartKingdomGUI) {
                            // The guild was awaiting automatic generation but the gamerule has since been
                            // disabled; fall back to the legacy start screen so a guild can still be built.
                            Player entity = Minecraft.getInstance().player;
                            if (entity == null) return;
                            Minecraft.getInstance().setScreen(new ScreenStartConquest(worldName, file, entity));
                        } else {
                            if (TaleOfKingdoms.CONFIG.mainConfig.alwaysShowUpdatesGUI || instance.didUpgrade()) {
                                Minecraft.getInstance().setScreen(new UpdateScreen());
                            } else if (TaleOfKingdoms.CONFIG.mainConfig.showContinueConquestGUI) {
                                Minecraft.getInstance().setScreen(new ScreenContinueConquest(instance));
                            }

                            if (api.getConquestInstanceStorage().getConquestInstance(worldName).isEmpty()) {
                                TaleOfKingdoms.LOGGER.info("Adding world: " + worldName);
                                api.getConquestInstanceStorage().addConquest(worldName, instance, true);
                            }
                        }
                    });

                    if (instance != null) {
                        TaleOfKingdoms.LOGGER.info("Adding early existing world: " + worldName);
                        api.getConquestInstanceStorage().addConquest(worldName, instance, true);
                    }

                    postJoin.add(runnable);
                } catch (JsonSyntaxException | JsonIOException | IOException e) {
                    e.printStackTrace();
                }
                return;
            }

            // New world creation
            postJoin.add(() -> api.executeOnMain(() -> {
                Player entity = Minecraft.getInstance().player;
                if (entity == null) return;
                if (shouldAutoGenerateGuild()) {
                    createAutoGeneratedInstance(api, worldName, entity);
                } else {
                    Minecraft.getInstance().setScreen(new ScreenStartConquest(worldName, file, entity));
                }
            }));
        });

        GameJoinCallback.EVENT.register(() -> {
            if (!Minecraft.getInstance().getConnection().getConnection().isMemoryConnection()) {
                postJoin.clear();
                return;
            }

            // Check player is loaded, then check if it's them or not, and whether they've already been registered. If all conditions met, add to joined list.
            if (joined) {
                postJoin.clear();
                return;
            }
            this.joined = true;

            for (Runnable runnable : postJoin) {
                runnable.run();
            }

            postJoin.clear();
        });
    }

    /**
     * Whether the {@code autoGenerateGuild} gamerule is enabled. This listener only acts on
     * integrated servers (see the memory connection check on game join), so the server's game
     * rules are always accessible here.
     */
    public static boolean shouldAutoGenerateGuild() {
        final MinecraftServer server = Minecraft.getInstance().getSingleplayerServer();
        return server != null && server.getGameRules().getBoolean(TOKGameRules.AUTO_GENERATE_GUILD);
    }

    /**
     * Starts the conquest without any player interaction: the guild generates naturally as a
     * structure, and the conquest is named when the player signs the contract with the Guild Master.
     */
    private void createAutoGeneratedInstance(TaleOfKingdomsAPI api, String worldName, Player player) {
        TaleOfKingdoms.LOGGER.info("Guild will generate automatically; starting conquest for world: " + worldName);
        ConquestInstance instance = new ConquestInstance(null, null, null, null);
        instance.reset(player);
        instance.setLoaded(true);
        api.getConquestInstanceStorage().addConquest(worldName, instance, true);
        instance.save(worldName);
        player.displayClientMessage(Component.translatable("generic.taleofkingdoms.guild_will_generate"), false);
    }

    private boolean load(String worldName, TaleOfKingdomsAPI api) {
        File file = new File(api.getDataFolder() + "worlds/" + worldName + ConquestInstance.FILE_TYPE);
        // Check if this world has been loaded or not
        if (!file.exists()) {
            try {
                // If not, create new file
                return file.createNewFile();
            } catch (IOException e) {
                e.printStackTrace();
            }
            return false;
        } else {
            // It already exists.
            return true;
        }
    }
}
